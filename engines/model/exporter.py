"""
AFE — Standalone PyTorch Code Generator & Exporter

Generates production-grade, zero-dependency `model.py` and `config.json`
files from any compiled `ArchitectureConfig` definition.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Dict, Any

from engines.model.config import ArchitectureConfig


class ModelExporter:
    """Produces clean, standalone Python source code and JSON metadata."""

    @staticmethod
    def generate_pytorch_code(cfg: ArchitectureConfig) -> str:
        """Generate a complete, self-contained model.py file."""
        return f'''# Auto-generated by AI Foundry Enterprise (AFE) Model Compiler
# Architecture: {cfg.name} (Tier: {cfg.tier})
# Total Parameters: {cfg.name}
import math
import torch
import torch.nn as nn
import torch.nn.functional as F

CONFIG = {json.dumps(cfg.to_dict(), indent=4)}

class RMSNorm(nn.Module):
    def __init__(self, dim: int, eps: float = {cfg.norm_eps}):
        super().__init__()
        self.eps = eps
        self.weight = nn.Parameter(torch.ones(dim))

    def forward(self, x):
        variance = x.pow(2).mean(-1, keepdim=True)
        return x * torch.rsqrt(variance + self.eps) * self.weight


class RotaryEmbedding(nn.Module):
    def __init__(self, dim: int, max_seq_len: int = {cfg.max_seq_len}, base: float = {cfg.rope_theta}):
        super().__init__()
        self.dim = dim
        inv_freq = 1.0 / (base ** (torch.arange(0, dim, 2).float() / dim))
        self.register_buffer("inv_freq", inv_freq, persistent=False)

    def forward(self, x, seq_len: int):
        t = torch.arange(seq_len, device=x.device, dtype=self.inv_freq.dtype)
        freqs = torch.outer(t, self.inv_freq)
        emb = torch.cat((freqs, freqs), dim=-1)
        return emb.cos(), emb.sin()


def apply_rotary_pos_emb(x, cos, sin):
    d_k = x.shape[-1]
    x1 = x[..., : d_k // 2]
    x2 = x[..., d_k // 2 :]
    rotate_half = torch.cat((-x2, x1), dim=-1)
    return (x * cos) + (rotate_half * sin)


class GroupedQueryAttention(nn.Module):
    def __init__(self, d_model: int = {cfg.d_model}, num_heads: int = {cfg.num_heads}, num_kv_heads: int = {cfg.num_kv_heads}, head_dim: int = {cfg.head_dim}):
        super().__init__()
        self.d_model = d_model
        self.num_heads = num_heads
        self.num_kv_heads = num_kv_heads
        self.head_dim = head_dim
        self.q_proj = nn.Linear(d_model, num_heads * head_dim, bias=False)
        self.k_proj = nn.Linear(d_model, num_kv_heads * head_dim, bias=False)
        self.v_proj = nn.Linear(d_model, num_kv_heads * head_dim, bias=False)
        self.o_proj = nn.Linear(num_heads * head_dim, d_model, bias=False)
        self.q_norm = RMSNorm(head_dim)
        self.k_norm = RMSNorm(head_dim)

    def forward(self, x, cos=None, sin=None, mask=None):
        B, L, _ = x.shape
        q = self.q_norm(self.q_proj(x).view(B, L, self.num_heads, self.head_dim))
        k = self.k_norm(self.k_proj(x).view(B, L, self.num_kv_heads, self.head_dim))
        v = self.v_proj(x).view(B, L, self.num_kv_heads, self.head_dim)

        if cos is not None and sin is not None:
            q = apply_rotary_pos_emb(q, cos[:L], sin[:L])
            k = apply_rotary_pos_emb(k, cos[:L], sin[:L])

        if self.num_heads != self.num_kv_heads:
            repeats = self.num_heads // self.num_kv_heads
            k = k.repeat_interleave(repeats, dim=2)
            v = v.repeat_interleave(repeats, dim=2)

        q, k, v = q.transpose(1, 2), k.transpose(1, 2), v.transpose(1, 2)
        out = F.scaled_dot_product_attention(q, k, v, attn_mask=mask, is_causal=(mask is None))
        return self.o_proj(out.transpose(1, 2).contiguous().view(B, L, -1))


class SwiGLUFeedForward(nn.Module):
    def __init__(self, d_model: int = {cfg.d_model}, intermediate_size: int = {cfg.intermediate_size}):
        super().__init__()
        self.gate_proj = nn.Linear(d_model, intermediate_size, bias=False)
        self.up_proj = nn.Linear(d_model, intermediate_size, bias=False)
        self.down_proj = nn.Linear(intermediate_size, d_model, bias=False)

    def forward(self, x):
        return self.down_proj(F.silu(self.gate_proj(x)) * self.up_proj(x))


class AFEModel(nn.Module):
    def __init__(self):
        super().__init__()
        self.embed_tokens = nn.Embedding({cfg.vocab_size}, {cfg.d_model})
        self.rope = RotaryEmbedding({cfg.head_dim}, max_seq_len={cfg.max_seq_len})
        self.layers = nn.ModuleList([
            nn.ModuleDict({{
                "norm1": RMSNorm({cfg.d_model}),
                "attn": GroupedQueryAttention(),
                "norm2": RMSNorm({cfg.d_model}),
                "ffn": SwiGLUFeedForward(),
            }}) for _ in range({cfg.num_layers})
        ])
        self.final_norm = RMSNorm({cfg.d_model})
        self.lm_head = nn.Linear({cfg.d_model}, {cfg.vocab_size}, bias=False)

    def forward(self, input_ids):
        B, L = input_ids.shape
        x = self.embed_tokens(input_ids)
        cos, sin = self.rope(x, L)
        for layer in self.layers:
            x = x + layer["attn"](layer["norm1"](x), cos=cos, sin=sin)
            x = x + layer["ffn"](layer["norm2"](x))
        return self.lm_head(self.final_norm(x))

if __name__ == "__main__":
    model = AFEModel()
    sample_ids = torch.randint(0, {cfg.vocab_size}, (1, 32))
    logits = model(sample_ids)
    print("Model forward pass successful. Output logits shape:", logits.shape)
'''

    @staticmethod
    def generate_config_json(cfg: ArchitectureConfig) -> str:
        """Produce JSON configuration manifest."""
        return json.dumps(cfg.to_dict(), indent=2)
